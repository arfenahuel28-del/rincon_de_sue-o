create extension if not exists pgcrypto;

-- ---------- Tablas ----------
create table if not exists public.categories (
  id text primary key check (id ~ '^[a-z0-9-]+$'),
  name text not null check (char_length(name) between 1 and 120),
  icon text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id text primary key check (id ~ '^[a-z0-9-]+$'),
  name text not null check (char_length(name) between 1 and 160),
  description text not null default '' check (char_length(description) <= 500),
  price numeric(12,2) not null check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  sold_out boolean not null default false,
  category_id text not null references public.categories(id),
  featured boolean not null default false,
  active boolean not null default true,
  image_url text,
  art jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  created_at timestamptz not null default now()
);

create sequence if not exists public.order_number_seq start 1;
do $$ begin
  create type public.order_status as enum ('pendiente_pago','pago_aprobado','pago_rechazado','en_preparacion','enviado','entregado','cancelado');
exception when duplicate_object then null; end $$;
do $$ begin
  create type public.payment_status as enum ('pendiente','aprobado','rechazado');
exception when duplicate_object then null; end $$;

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  number text not null unique,
  idempotency_key text not null unique,
  created_at timestamptz not null default now(),
  customer_name text not null check (char_length(customer_name) between 2 and 160),
  customer_phone text not null check (char_length(customer_phone) between 8 and 30),
  customer_email text not null check (char_length(customer_email) between 5 and 160),
  delivery_method text not null check (delivery_method in ('retiro','envio')),
  delivery_address text not null default '',
  notes text not null default '',
  total numeric(12,2) not null check (total >= 0),
  status public.order_status not null default 'pendiente_pago',
  payment_status public.payment_status not null default 'pendiente',
  payment_provider text,
  provider_payment_id text,
  stock_restored_at timestamptz
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id text not null,
  name text not null,
  unit_price numeric(12,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity > 0),
  subtotal numeric(12,2) not null check (subtotal >= 0)
);

create index if not exists products_active_idx on public.products(active, featured);
create index if not exists products_category_idx on public.products(category_id);
create index if not exists orders_status_idx on public.orders(status, created_at desc);
create index if not exists order_items_order_idx on public.order_items(order_id);

-- ---------- updated_at automático ----------
create or replace function public.touch_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin new.updated_at = now(); return new; end;
$$;
drop trigger if exists products_touch_updated_at on public.products;
create trigger products_touch_updated_at before update on public.products
  for each row execute function public.touch_updated_at();

-- ---------- ¿El usuario actual es administrador? ----------
-- Debe poder ejecutarla cualquiera (también anon): la usan las políticas de lectura.
-- Para quien no está en admin_users devuelve false.
create or replace function public.is_admin() returns boolean
language sql security definer set search_path = public as $$
  select exists (select 1 from public.admin_users where user_id = auth.uid());
$$;

